def run_epoch(model, loader, criterion=None, optimizer=None, train=True):
    """
    Run a single epoch of training or validation. When called, the caller can
    specify whether they want to update the model's parameters (train=True) or
    not (train=False).

    Arguments:
      model: the model to train or evaluate
      loader: the dataloader for the dataset (training or validaiton)
      criterion: the loss function (only used as a statistic for validation)
      optimizer: the optimizer (only used in training)

    Returns:
      avg_loss: the average loss over the epoch
      accuracy: the accuracy over the epoch
      f1: the f1 score over the epoch
    """
    model.train(train)
    total_loss, correct, total = 0.0, 0, 0
    all_preds, all_targets = [], []

    loop = tqdm(loader, desc="Training" if train else "Validation", leave=True)
    for data, targets in loop:
        data, targets = data.to(device), targets.to(device)

        outputs = model(data)
        loss = criterion(outputs, targets)

        if train:

            optimizer.zero_grad()
            loss.backward() # Backpropogate the loss
            optimizer.step() # Step the optimizer

        total_loss += loss.item()
        _, preds = outputs.max(1)
        total += targets.size(0)
        correct += preds.eq(targets).sum().item()
        all_preds.extend(preds.cpu().numpy())
        all_targets.extend(targets.cpu().numpy())

        acc = 100 * correct / total
        loop.set_postfix(Loss=f"{loss.item():.4f}", Acc=f"{acc:.2f}%")

    avg_loss = total_loss / len(loader)
    accuracy = 100 * correct / total
    f1 = f1_score(all_targets, all_preds, average="macro")
    return avg_loss, accuracy, f1

