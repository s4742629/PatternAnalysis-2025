def plot_learning_curves(train_losses, val_losses, train_accuracies, val_accuracies, val_f1s):
    """
    Plot the learning curves for the model, including a plot of the accuracy and
    loss for the training set vs. the validation set as well as a plot of the
    validation set's f1 scores.

    Arguments:
      train_losses: a list of the training losses for each epoch
      val_losses: a list of the validation losses for each epoch
      train_accuracies: a list of the training accuracies for each epoch
      val_accuracies: a list of the validation accuracies for each epoch
      val_f1s: a list of the validation f1 scores for each epoch
    """
    epochs = range(1, len(train_losses) + 1)
    plt.figure(figsize=(18, 5))

    # Training vs. validation loss each epoch
    plt.subplot(1, 3, 1)
    plt.plot(epochs, train_losses, "r-", label="Train Loss")
    plt.plot(epochs, val_losses, "g-", label="Validation Loss")
    plt.title("Training vs Validation Loss")
    plt.xlabel("Epoch")
    plt.ylabel("Loss")
    plt.grid(True)
    plt.legend()

    # Training vs. validation accuracy each epoch
    plt.subplot(1, 3, 2)
    plt.plot(epochs, train_accuracies, "r-", label="Train Accuracy")
    plt.plot(epochs, val_accuracies, "g-", label="Validation Accuracy")
    plt.title("Training vs Validation Accuracy")
    plt.xlabel("Epoch")
    plt.ylabel("Accuracy (%)")
    plt.grid(True)
    plt.legend()

    # Validation f1 score each epoch
    plt.subplot(1, 3, 3)
    plt.plot(epochs, val_f1s, "-b", label="Validation F1 Score")
    plt.title("Validation F1 Score")
    plt.xlabel("Epoch")
    plt.ylabel("F1 Score")
    plt.grid(True)
    plt.legend()

    plt.tight_layout()
    plt.show()

