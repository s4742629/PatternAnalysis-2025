class ADNIDataset(Dataset):
    """
    Custom dataset class for ADNI brain MRI images.
    """
    def __init__(self, root_dir, transform=None):
        """
        Initialize the dataset. Creates a dictionary of labels and a list of
        classes.

        Arguments:
          root_dir: Path to the directory containing the dataset in question.
          transform: Transforms to be applied to the samples in the dataset.
        """
        self.root_dir = root_dir
        self.transform = transform
        self.class_to_idx = {'AD': 0, 'NC': 1}
        self.classes = list(self.class_to_idx.keys())
        self.samples = []

        for cls in self.classes:
            class_dir = os.path.join(root_dir, cls)
            if not os.path.isdir(class_dir):
                continue
            label = self.class_to_idx[cls]
            for fname in os.listdir(class_dir):
                if fname.lower().endswith(('.png', '.jpg', '.jpeg', '.bmp')):
                    pid = self._extract_patient_id(fname)
                    self.samples.append((os.path.join(class_dir, fname), label, pid))

    def _extract_patient_id(self, filename):
        """
        Extract the ID of a patient for a specific MRI image, given the
        filename.

        Arguments:
          filename: Name of the image file.

        Returns:
          Patient ID if found, otherwise nothing.
        """
        m = re.match(r"(\d{6})", filename)
        return m.group(1) if m else None

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        path, label, _ = self.samples[idx]
        image = Image.open(path).convert("L") # Converts images to grayscale
        if self.transform:
            image = self.transform(image)
        return image, label

def patient_level_split(dataset, test_size=0.2, random_state=42):
    """
    Split the dataset into training and validation sets based on patient IDs,
    stratifying according to labels as well.

    Arguments:
      dataset: the base set of images to be split into training and validation sets.
      test_size: the proportion of the dataset to include in the validation set.
      random_state: the seed used by the random number generator for splitting the data.

    Returns:
      train_idx: a list of indices of the training samples.
      val_idx: a list of indices of the validation samples.
    """
    patient_to_indices = defaultdict(list)
    for idx, (_, label, pid) in enumerate(dataset.samples):
        if pid:
            patient_to_indices[pid].append(idx)
    unique_pids = list(patient_to_indices.keys())
    labels = [dataset.samples[patient_to_indices[pid][0]][1] for pid in unique_pids]

    train_pids, val_pids = train_test_split(unique_pids, test_size=test_size,
                                            random_state=random_state, stratify=labels)
    train_idx = [i for pid in train_pids for i in patient_to_indices[pid]]
    val_idx = [i for pid in val_pids for i in patient_to_indices[pid]]
    return train_idx, val_idx

def get_adni_transforms(mean=0.263, std=0.271):
    """
    Composes transforms for the training and validation/test sets. Random
    transforms are included in the training set to augment the dataset. For the
    validation and test sets, only consistent transforms are used.

    Arguments:
      mean: the mean of the dataset for normalisation purposes
      std: the standard deviation of the dataset for normalisation purposes

    Returns:
      train_tf: the composed training transforms
      eval_tf: the composed evaluation transforms for validation and testing
    """
    train_tf = transforms.Compose([
        transforms.Pad((8, 0, 8, 0)),
        transforms.RandomResizedCrop(256, scale=(0.8, 1.0)),
        transforms.RandomHorizontalFlip(p=0.5),
        transforms.RandomRotation(10),
        transforms.GaussianBlur(kernel_size=3, sigma=(0.1, 1.0)),
        transforms.ColorJitter(brightness=0.1, contrast=0.1),
        transforms.RandomAffine(degrees=0, translate=(0.05, 0.05)),
        transforms.ToTensor(),
        transforms.RandomErasing(p=0.2, scale=(0.01, 0.05)),
        transforms.Normalize(mean=[mean], std=[std]),
    ])
    eval_tf = transforms.Compose([
        transforms.Pad((8, 0, 8, 0)),
        transforms.Resize((256, 256)),
        transforms.ToTensor(),
        transforms.Normalize(mean=[mean], std=[std]),
    ])
    return train_tf, eval_tf

def create_datasets(train_dir, test_dir, val_split=0.2):
    """
    Create the training, validation, and testing datasets using the ADNIDataset
    class and patient_level_split function defined earlier.

    Arguments:
      train_dir: Path to the directory containing the training images.
      test_dir: Path to the directory containing the testing images.
      val_split: Proportion of the training data to be used for the validation set.

    Returns:
      train_ds: Compiled training dataset
      val_ds: Compiled validation dataset
      test_ds: Compiled testing dataset
    """
    train_tf, eval_tf = get_adni_transforms()
    base_dataset = ADNIDataset(train_dir)
    train_idx, val_idx = patient_level_split(base_dataset, val_split)
    train_ds = Subset(ADNIDataset(train_dir, train_tf), train_idx)
    val_ds   = Subset(ADNIDataset(train_dir, eval_tf), val_idx)
    test_ds  = ADNIDataset(test_dir, eval_tf)
    return train_ds, val_ds, test_ds

def create_dataloaders(train_ds, val_ds, test_ds, batch_size=128, num_workers=8):
    """
    Create the dataloaders for the training, validation, and testing datasets
    which can then be used for training/evaluating the model.

    Arguments:
      train_ds: Compiled training dataset
      val_ds: Compiled validation dataset
      test_ds: Compiled testing dataset
      batch_size: Batch size for the dataloaders
      num_workers: Number of workers for the dataloaders

    Returns:
      train_loader: Dataloader for the training dataset
      val_loader: Dataloader for the validation dataset
      test_loader: Dataloader for the testing dataset
    """
    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True, num_workers=num_workers)
    val_loader   = DataLoader(val_ds,   batch_size=batch_size, shuffle=False, num_workers=num_workers)
    test_loader  = DataLoader(test_ds,  batch_size=batch_size, shuffle=False, num_workers=num_workers)
    return train_loader, val_loader, test_loader

def count_classes(dataset, name="Dataset"):
    """
    Count the number of samples per class in a dataset. Displays the total
    number of samples in the dataset as well as a class breakdown. Also
    calculates the class weights for the loss criterion.

    Arguments:
      dataset: the dataset to count the samples and class instances of as well as calculate class weights for
      name: the name of the dataset to be printed alongside the counted samples and class instances

    Returns:
      class_weights: the class weights for the loss criterion
    """
    if isinstance(dataset, torch.utils.data.Subset):
        # Access underlying dataset and the indices
        targets = np.array([dataset.dataset.samples[i][1] for i in dataset.indices])
    else:
        # Direct ImageFolder dataset
        targets = np.array([s[1] for s in dataset.samples])

    class_weights = []

    counts = Counter(targets)
    print(f"\n{name} class distribution:")
    for cls_idx, count in counts.items(): # Calculate the weight for each class in the dataset
        class_name = dataset.dataset.classes[cls_idx] if isinstance(dataset, torch.utils.data.Subset) else dataset.classes[cls_idx]
        print(f"  {class_name}: {count}")

        class_weights.append(len(targets)/(len(counts.items())*count))

    print(f"  Total: {len(targets)}")

    return class_weights

def show_samples(dataset, num_samples=10, title="Sample Images"):
    """
    Display a specified number of random samples from the dataset. The samples
    are denormalised prior to being displayed

    Arguments:
      dataset: the dataset to display samples from
      num_samples: the number of samples to display
      title: the title of the plot
    """
    fig, axes = plt.subplots(2, 5, figsize=(12, 6))
    fig.suptitle(title, fontsize=16)

    for i in range(num_samples):
        image, label = dataset[random.randint(0, len(dataset)-1)]
        row, col = divmod(i, 5)
        image = image * 0.271 + 0.263  # Denormalize the image using the mean and standard deviation
        image = image.squeeze(0)
        axes[row, col].imshow(image, cmap='gray')
        axes[row, col].set_title(f'Label: {label}')
        axes[row, col].axis('off')

    plt.tight_layout()
    plt.show()